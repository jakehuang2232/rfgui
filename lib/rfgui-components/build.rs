use std::collections::{BTreeMap, BTreeSet, HashSet};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const CODEPOINTS_PATH: &str = "assets/MaterialSymbolsOutlined.codepoints";
const FONT_PATH: &str = "assets/MaterialSymbolsOutlined.ttf";
const FAMILY_PREFIX: &str = "Material Symbols Outlined";
const POSTSCRIPT_PREFIX: &str = "MaterialSymbolsOutlined";
const GLYPH_FONT_DIR: &str = "material_symbols";

fn main() {
    println!("cargo:rerun-if-changed={CODEPOINTS_PATH}");
    println!("cargo:rerun-if-changed={FONT_PATH}");

    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("missing CARGO_MANIFEST_DIR");
    let manifest_dir = Path::new(&manifest_dir);
    let out_dir = env::var("OUT_DIR").expect("missing OUT_DIR");
    let out_dir = Path::new(&out_dir);

    let codepoints = fs::read_to_string(manifest_dir.join(CODEPOINTS_PATH))
        .expect("failed to read Material Symbols codepoints");
    let symbols = parse_codepoints(&codepoints);

    // Every symbol becomes its own single-glyph variable font. Each generated
    // icon component references only its own font, so the linker drops the
    // font data of every icon an application never renders.
    let font_bytes =
        fs::read(manifest_dir.join(FONT_PATH)).expect("failed to read Material Symbols font");
    let font = SourceFont::parse(&font_bytes).expect("failed to parse Material Symbols font");
    let glyph_font_dir = out_dir.join(GLYPH_FONT_DIR);
    fs::create_dir_all(&glyph_font_dir).expect("failed to create Material Symbols font directory");
    let codepoint_set: BTreeSet<u32> = symbols.iter().map(|symbol| symbol.codepoint).collect();
    for &codepoint in &codepoint_set {
        let glyph_font = font.glyph_font(codepoint).unwrap_or_else(|err| {
            panic!("failed to subset Material Symbol U+{codepoint:04X}: {err}")
        });
        fs::write(glyph_font_dir.join(glyph_font_file(codepoint)), glyph_font)
            .expect("failed to write Material Symbol font");
    }

    let generated = generate_module(&symbols, &codepoint_set);
    fs::write(out_dir.join("material_symbols_outlined.rs"), generated)
        .expect("failed to write generated Material Symbols module");
}

struct Symbol<'a> {
    ligature: &'a str,
    codepoint: u32,
}

fn parse_codepoints(codepoints: &str) -> Vec<Symbol<'_>> {
    codepoints
        .lines()
        .filter_map(|line| {
            let mut parts = line.split_whitespace();
            let ligature = parts.next()?.trim();
            if ligature.is_empty() {
                return None;
            }
            let codepoint = parts
                .next()
                .and_then(|value| u32::from_str_radix(value, 16).ok())
                .unwrap_or_else(|| panic!("missing or invalid codepoint for `{ligature}`"));
            Some(Symbol {
                ligature,
                codepoint,
            })
        })
        .collect()
}

fn family_name(codepoint: u32) -> String {
    format!("{FAMILY_PREFIX} {codepoint:04X}")
}

fn postscript_name(codepoint: u32) -> String {
    format!("{POSTSCRIPT_PREFIX}-{codepoint:04X}")
}

fn glyph_font_file(codepoint: u32) -> String {
    format!("{codepoint:04x}.ttf")
}

fn glyph_static_name(codepoint: u32) -> String {
    format!("MATERIAL_SYMBOL_{codepoint:04X}")
}

fn generate_module(symbols: &[Symbol<'_>], codepoints: &BTreeSet<u32>) -> String {
    let mut output = String::new();
    output.push_str("// @generated by lib/rfgui-components/build.rs\n");
    output.push('\n');

    for &codepoint in codepoints {
        let _ = write!(
            output,
            "static {static_name}: MaterialSymbolGlyph = MaterialSymbolGlyph::new(\n    \
             \"{family}\",\n    \
             \"\\u{{{codepoint:x}}}\",\n    \
             include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{GLYPH_FONT_DIR}/{file}\")),\n\
             );\n\n",
            static_name = glyph_static_name(codepoint),
            family = family_name(codepoint),
            file = glyph_font_file(codepoint),
        );
    }

    let mut used = HashSet::new();
    for symbol in symbols {
        let component_name = unique_component_name(to_component_name(symbol.ligature), &mut used);
        let static_name = glyph_static_name(symbol.codepoint);
        output.push_str(&format!("pub struct {component_name};\n\n"));
        output.push_str(&format!(
            "impl rfgui::ui::RsxComponent<MaterialSymbolIconProps> for {component_name} {{\n"
        ));
        output.push_str(
            "    fn render(props: MaterialSymbolIconProps, _children: Vec<rfgui::ui::RsxNode>) -> rfgui::ui::RsxNode {\n",
        );
        output.push_str(&format!(
            "        render_material_symbol_icon(&{static_name}, props)\n"
        ));
        output.push_str("    }\n");
        output.push_str("}\n\n");
        output.push_str("#[rfgui::ui::component]\n");
        output.push_str(&format!("impl rfgui::ui::RsxTag for {component_name} {{\n"));
        output.push_str("    type Props = __MaterialSymbolIconPropsInit;\n");
        output.push_str("    type StrictProps = MaterialSymbolIconProps;\n");
        output.push_str("    const ACCEPTS_CHILDREN: bool = false;\n");
        output.push_str(
            "    fn into_strict(props: Self::Props) -> Self::StrictProps { props.into() }\n",
        );
        output.push_str("    fn create_node(\n");
        output.push_str("        props: Self::StrictProps,\n");
        output.push_str("        children: Vec<rfgui::ui::RsxNode>,\n");
        output.push_str("        _key: Option<rfgui::ui::RsxKey>,\n");
        output.push_str("    ) -> rfgui::ui::RsxNode {\n");
        output.push_str(&format!(
            "        <Self as rfgui::ui::RsxComponent<MaterialSymbolIconProps>>::render(props, children)\n"
        ));
        output.push_str("    }\n");
        output.push_str("}\n\n");
    }

    output
}

fn unique_component_name(base: String, used: &mut HashSet<String>) -> String {
    if used.insert(base.clone()) {
        return base;
    }

    let mut index = 2_u32;
    loop {
        let candidate = format!("{base}{index}");
        if used.insert(candidate.clone()) {
            return candidate;
        }
        index += 1;
    }
}

fn to_component_name(ligature: &str) -> String {
    let mut ident = String::new();
    for segment in ligature.split('_').filter(|segment| !segment.is_empty()) {
        push_segment(&mut ident, segment);
    }

    if ident.is_empty() {
        ident.push_str("MaterialSymbol");
    }

    if ident
        .as_bytes()
        .first()
        .is_some_and(|byte| byte.is_ascii_digit())
    {
        ident.insert_str(0, "Icon");
    }

    ident.push_str("Icon");
    ident
}

fn push_segment(output: &mut String, segment: &str) {
    let mut chunk = String::new();

    for character in segment.chars() {
        if character.is_ascii_alphanumeric() {
            chunk.push(character);
            continue;
        }

        flush_chunk(output, &mut chunk);
    }

    flush_chunk(output, &mut chunk);
}

fn flush_chunk(output: &mut String, chunk: &mut String) {
    if chunk.is_empty() {
        return;
    }

    let mut chars = chunk.chars();
    if let Some(first) = chars.next() {
        output.push(first.to_ascii_uppercase());
        output.push_str(chars.as_str());
    }
    chunk.clear();
}

